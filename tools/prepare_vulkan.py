#!/usr/bin/env python3
"""Write vulkan_prebuilt/: libann's compiled Vulkan shaders and the Vulkan headers.

Builds with USE_VULKAN then need neither glslc nor the Vulkan SDK (see the
USE_VULKAN block in CMakeLists.txt). CI runs this once, on a machine with the
Vulkan SDK or libvulkan-dev and glslc installed, and hands the result to the
wheel builds and the sdist.

    python tools/prepare_vulkan.py [--license PATH] [--out DIR]

--license copies the Vulkan headers' license file into the output, so it
ships alongside them (on Debian/Ubuntu: /usr/share/doc/libvulkan-dev/copyright).
"""

import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def cmake_cache_value(cache: Path, name: str) -> str:
    match = re.search(rf"^{name}:[^=]*=(.*)$", cache.read_text(), re.MULTILINE)
    return match.group(1).strip() if match else ""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=ROOT / "vulkan_prebuilt")
    parser.add_argument("--license", type=Path, help="license file of the Vulkan headers")
    args = parser.parse_args()

    build = ROOT / "build" / "vk-prebuilt"
    subprocess.run(["cmake", "-S", str(ROOT), "-B", str(build), "-DUSE_VULKAN=ON",
                    # always compile the shaders, never reuse an earlier output
                    f"-DPYANN_VULKAN_PREBUILT={build / 'none'}"], check=True)
    subprocess.run(["cmake", "--build", str(build), "--target", "pyann_vk_shaders"], check=True)

    include = Path(cmake_cache_value(build / "CMakeCache.txt", "Vulkan_INCLUDE_DIR"))
    if not (include / "vulkan" / "vulkan.h").exists():
        sys.exit(f"Vulkan headers not found (Vulkan_INCLUDE_DIR={include})")

    if args.out.exists():
        shutil.rmtree(args.out)
    (args.out / "include").mkdir(parents=True)
    shutil.copy2(build / "vk_spv" / "shaders_vk_spv.h", args.out)
    # vulkan.h includes vk_platform.h, vulkan_core.h and, in newer headers,
    # vk_video/. Only the C headers: the C++ ones are most of the size
    for sub in ("vulkan", "vk_video"):
        if (include / sub).is_dir():
            (args.out / "include" / sub).mkdir()
            for header in (include / sub).glob("*.h"):
                shutil.copy2(header, args.out / "include" / sub)
    if args.license:
        shutil.copy2(args.license, args.out / "LICENSE-Vulkan-Headers.txt")

    ann_commit = subprocess.run(["git", "-C", str(ROOT / "ann"), "rev-parse", "HEAD"],
                                capture_output=True, text=True).stdout.strip()
    (args.out / "README.txt").write_text(
        "Generated by tools/prepare_vulkan.py; do not edit.\n"
        f"Shaders compiled from ann/ at {ann_commit or 'unknown commit'}.\n"
        f"Headers copied from {include}.\n")
    print(f"Wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
